-- ==============================================================
-- V2: ストレス関連機能の撤廃に伴うデータクリーンアップ
--
-- 労働安全衛生法上のストレスチェック制度(第66条の10)と紛らわしい外形
-- (心理的な負担の程度を個別に測定・表示する機能)を作らないため、
-- アプリからストレス度の測定・表示・アラートを完全に削除した
-- (docs/health-audit-legal-checklist.md 参照)。
--
-- このマイグレーションはこれまでのV1__baseline.sqlと異なり、実際にデータを
-- 変更する(このアプリで初めての、意図的なデータ削除・書き換えマイグレーション)。
-- 対象は「ストレス度」に関する値そのものであり、それ以外の健康データ
-- (体調・睡眠・疲労・運動・体温・メモ等)には一切手を付けない。
--
-- 1. health_alert: これまでに生成された「ストレス度が高い状態の継続」アラートを削除する。
--    アプリ側は HealthAlertType.HIGH_STRESS を引き続き列挙型に残しているが
--    (既存行のデシリアライズを壊さないための保険。新規に生成することは無い)、
--    このアラート自体は「ストレスが高い」という判定結果そのものであり、
--    ストレスチェック的な外形を最も強く持つデータのため、明示的に削除する。
-- 2. health_check.stress_level / health_profile.stress_level: 列自体は
--    (他の機能と同様、既存データ保護のため)残すが、アプリからは一切参照しなくなるため、
--    保持し続ける意味がない。念のため値をNULLにクリアする(列の削除(DROP COLUMN)は
--    行わない。他の撤廃済み機能と同じ方針)。
-- ==============================================================

DELETE FROM health_alert WHERE alert_type = 'HIGH_STRESS';

UPDATE health_check SET stress_level = NULL WHERE stress_level IS NOT NULL;

UPDATE health_profile SET stress_level = NULL WHERE stress_level IS NOT NULL;
