package com.kinn.app.entity;

/**
 * 健康管理監査ログの対象リソース種別。既存の /api/health/**, /api/admin/health/** の
 * エンドポイントに1対1で対応する(AUDIT_LOGのみ例外で、監査ログ自体の閲覧を指す)。
 */
public enum HealthAuditResource {
    /** 健康プロフィール(身長・体重・血圧などのベースライン情報) */
    PROFILE,
    /** 今日の体調チェック */
    DAILY_CHECK,
    /** 体調チェック履歴 */
    HISTORY,
    /** 健康スコア */
    SCORE,
    /** 健康スコア・体重・睡眠などの推移グラフ */
    TREND,
    /**
     * 健康アラート(廃止済み)。
     * 健康管理機能は診断・治療の提案を行わず記録・閲覧・可視化のみに限定する方針のため、
     * アラート機能自体(生成・表示API・health_alertテーブルへの書き込み)を撤廃した
     * (2026-08-30、docs/health-audit-legal-checklist.md参照)。過去に生成された監査ログの
     * resource列にはこの値の行が残っており、{@code @Enumerated(EnumType.STRING)}での
     * デシリアライズを壊さないよう列挙型からは削除せずここに残している。新規に
     * このリソースへの監査ログが記録されることはない。
     */
    ALERT,
    /** 勤怠×健康分析 */
    ANALYSIS,
    /** 月次健康記録(従来画面。日次データの一括保存・1日分保存/削除を含む) */
    MONTHLY_RECORD,
    /**
     * 管理者向け健康ダッシュボード(廃止済み。会社・部署単位の集計。個人非紐付け)。
     * ポートフォリオとしての位置づけ上、健康管理は管理者が確認するものではなく個人が
     * 自由に記録するものに限定する方針としたため、管理者向け集計ダッシュボード機能自体
     * (`AdminHealthController`/`AdminHealthService`/admin-health.html)を撤廃した
     * (2026-08-30)。ALERTと同じ理由で、過去の監査ログのデシリアライズを壊さないよう
     * 列挙型からは削除せずここに残している。新規にこのリソースへの監査ログが
     * 記録されることはない。
     */
    ADMIN_DASHBOARD,
    /** 監査ログそのものの閲覧(自分専用ログ画面・管理者検索画面) */
    AUDIT_LOG
}
