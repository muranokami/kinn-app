package com.kinn.app.dto;

/**
 * トップページの自動休憩機能(休憩開始ボタン)の現在の状態。
 * 永続化はしない(AttendanceRecordのstartTime/endTime/breakStartTime/breakEndTime/breakMinutesから
 * その都度サーバー側で導出する。DBにはこの列挙自体を保存しない)。
 *
 * 休憩は1日に何回でも分けて取れる(刻んで取る運用に対応するため、1回で使い切らなくてもよい)。
 * そのため「休憩を1回終えた」だけでは終端状態にはならず、本日の合計が上限(既定60分)に
 * 達するまでは何度でもWORKINGに戻って再度休憩を開始できる。
 */
public enum BreakStatus {
    /**
     * 休憩を開始できる状態(現在休憩中ではない、未退勤、かつ本日の休憩予算が残っている)。
     * 出勤時刻(start_time)の入力は前提にしない: 当日の勤怠レコードが無くても、
     * または出勤時刻が未入力でもこの状態になる。
     */
    WORKING,
    /** 休憩中(休憩開始時刻はあるが、その回の休憩終了時刻がまだない) */
    ON_BREAK,
    /** 本日の休憩予算(既定60分)を、1回または複数回に分けて使い切った状態。本日はもう休憩を開始できない */
    BREAK_EXHAUSTED,
    /** 本日は既に退勤済み */
    CLOCKED_OUT,
}
